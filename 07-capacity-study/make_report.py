"""Render result tables as markdown. Tables only: no prose conclusions.

    .venv/bin/python make_report.py --dir results/sim [--out results/sim/tables.generated.md]

The output starts with a GENERATED marker. The script overwrites only files that carry it, so a
hand-written report (REPORT.md) can never be clobbered. A value a source could not measure is
rendered ``not measured``. Output is labelled SIMULATED unless the result meta says otherwise.
"""
from __future__ import annotations

import argparse
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

import results_io
import stability

GENERATED_MARKER = "<!-- GENERATED by make_report.py: do not edit; overwritten on every run -->"
NOT_MEASURED = "not measured"
DEFAULT_NAME = "tables.generated.md"
PAIR_FOCUS = (("B", 64), ("B", 16), ("A", 64))  # before/after pairs worth showing in full
ABLATION_FOCUS = (("B", 64), ("A", 64))
TABLE_LINK = "nvlink"
TABLE_BATCH = 64


def fmt(value: float | None, digits: int = 1) -> str:
    if value is None:
        return NOT_MEASURED
    return f"{value:,.{digits}f}"


def _mean(summary: Mapping[str, Any], metric: str) -> float | None:
    stats = summary.get(metric)
    return None if stats is None else stats["mean"]


def _cell(text: str) -> str:
    """Make a value safe inside a markdown table cell (no pipes, no line breaks)."""
    return " ".join(str(text).split()).replace("|", "\\|")


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    lines = ["| " + " | ".join(_cell(h) for h in header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return lines + [""]


def _banner(meta: Mapping[str, Any]) -> list[str]:
    simulated = meta.get("simulated")
    if simulated is True:
        return ["> **SIMULATED.** Produced by the simulator in `03-batching-simulator` with a roofline cost model from "
                "illustrative GPU peaks. Not a GPU measurement; peak GPU memory is not measured.", ""]
    if simulated is False:
        return [f"> Measured with vLLM (`{meta.get('git_commit', 'unknown')}`); see the run metadata.", ""]
    return ["> **UNKNOWN PROVENANCE.** The result metadata does not say whether these numbers are simulated "
            "or measured. Do not quote them as measurements.", ""]


def _matrix_section(summaries: Sequence[Mapping[str, Any]], bottlenecks: Mapping[str, str]) -> list[str]:
    header = ["case", "reps", "TTFT mean ms", "TTFT p95 ms", "TPOT mean ms", "P95 e2e ms", "req/s",
              "out tok/s", "CV tok/s", "peak GPU mem GiB", "KV peak", "preempt", "peak wait", "bottleneck"]
    rows = []
    for s in summaries:
        cv = s["output_tok_s"]["cv"] if s["output_tok_s"] else None
        kv = _mean(s, "kv_peak_frac")
        rows.append([
            s["case_id"], str(s["n_reps"]), fmt(_mean(s, "mean_ttft_ms"), 0), fmt(_mean(s, "p95_ttft_ms"), 0),
            fmt(_mean(s, "mean_tpot_ms")), fmt(_mean(s, "p95_e2e_ms"), 0), fmt(_mean(s, "req_per_s"), 2),
            fmt(_mean(s, "output_tok_s"), 0), NOT_MEASURED if cv is None else f"{cv:.1%}",
            fmt(_mean(s, "peak_gpu_mem_gib")), NOT_MEASURED if kv is None else f"{kv:.0%}",
            fmt(_mean(s, "preemptions"), 0), fmt(_mean(s, "peak_waiting"), 0),
            bottlenecks.get(s["case_id"], "-"),
        ])
    return ["## Matrix (mean over repeats)", ""] + _table(header, rows)


def _stability_section(analysis: Mapping[str, Any]) -> list[str]:
    floors = analysis["noise_floor_pct"]
    lines = ["## Stability", "", "Noise floor (A/A delta, widened per comparison by each case's own CV):", ""]
    lines += _table(["metric", "noise floor %"], [[m, f"{v:.2f}"] for m, v in floors.items()])
    unstable = analysis["unstable"]
    lines += [f"Metrics with CV above the {stability.CV_FLAG:.0%} flag:", ""]
    lines += _table(["case", "unstable metrics"], [[c, ", ".join(m)] for c, m in unstable.items()]) \
        if unstable else ["none", ""]
    low = analysis["p95_low_sample"]
    lines += [f"Cases whose per-run P95 rests on fewer than {stability.P95_MIN_REQUESTS} requests (tail estimate is soft): "
              + (", ".join(low) if low else "none"), ""]
    return lines


def _decision_section(analysis: Mapping[str, Any]) -> list[str]:
    lines = ["## Objective and decision", "",
             f"Objective: maximize output tok/s subject to P95 e2e <= L, where L = k x baseline P95 e2e "
             f"at the lowest concurrency (k = {analysis['k_threshold']}).", ""]
    rows = [[d["workload"], fmt(d["threshold_ms"], 0), ", ".join(d["feasible"]) or "none",
             d["best_case"] or "none", NOT_MEASURED if d["delta_pct"] is None else f"{d['delta_pct']:+.1f}%",
             d["verdict"] or "-", d["recommendation"]] for d in analysis["decisions"]]
    lines += _table(["workload", "L ms", "feasible cells", "best cell", "tuned vs baseline",
                     "verdict", "recommendation"], rows)
    for workload, reason in analysis.get("skipped_workloads", {}).items():
        lines += [f"Workload {workload} was not analysed: {reason}", ""]
    return lines


def _pairs_section(analysis: Mapping[str, Any]) -> list[str]:
    lines = ["## Before / after (baseline -> tuned)", ""]
    for pair in analysis["pairs"]:
        if (pair["workload"], pair["concurrency"]) not in PAIR_FOCUS:
            continue
        lines += [f"### {pair['before']} -> {pair['after']}", ""]
        rows = [[r["metric"], fmt(r["before"], 2), fmt(r["after"], 2),
                 NOT_MEASURED if r["delta_pct"] is None else f"{r['delta_pct']:+.1f}%",
                 r["verdict"], r["direction"]] for r in pair["rows"]]
        lines += _table(["metric", "before", "after", "change", "verdict", "direction"], rows)
    return lines


def _bottleneck_section(analysis: Mapping[str, Any]) -> list[str]:
    rows = [[b["case_id"], b["label"], b["reason"] + (f" (caveat: {b['caveat']})" if b.get("caveat") else "")]
            for b in analysis["bottlenecks"]]
    return ["## Bottleneck labels (rule-based; see bottleneck.py)", ""] + _table(["case", "label", "evidence"], rows)


def _ablation_section(ablation: Sequence[Mapping[str, Any]] | None) -> list[str]:
    lines = ["## Ablation (SIMULATED; one knob at a time)", ""]
    if not ablation:
        return lines + ["No ablation results in this directory.", ""]
    focus = [s for s in ablation if (s["workload"], s["concurrency"]) in ABLATION_FOCUS]
    rows = [[s["case_id"], str(s["n_reps"]), fmt(_mean(s, "mean_ttft_ms"), 0), fmt(_mean(s, "mean_tpot_ms")),
             fmt(_mean(s, "p95_e2e_ms"), 0), fmt(_mean(s, "output_tok_s"), 0),
             fmt(_mean(s, "kv_peak_frac"), 2), fmt(_mean(s, "preemptions"), 0)] for s in focus]
    return lines + _table(["case", "reps", "TTFT ms", "TPOT ms", "P95 e2e ms", "tok/s", "KV peak", "preempt"], rows)


def _multi_gpu_section(rows: Sequence[Mapping[str, Any]]) -> list[str]:
    lines = ["## Multi-GPU (analytic; link constants ASSUMED, not measured)", "",
             f"Decode step with {TABLE_BATCH} sequences in the batch; KV capacity is group-wide.", ""]
    body = [[r["link"], str(r["tp"]), fmt(r["t_tp_ms"], 2), fmt(r["speedup"], 2), f"{r['comm_fraction']:.0%}",
             f"{r['pool_tokens_total']:,}", fmt(r["gain_vs_tp1"], 2)]
            for r in rows if r["batch_tokens"] == TABLE_BATCH]
    return lines + _table(["link", "TP", "step ms", "speedup", "comm share", "KV tokens", "KV gain"], body)


def render(directory: Path) -> str:
    analysis_file = results_io.read_results(directory / "analysis.json")
    analysis = analysis_file["rows"][0]
    meta = analysis_file["meta"]
    summary_path = directory / "matrix_summary.json"
    results_io.assert_fresh(summary_path, meta.get("matrix_summary_sha256"))
    summaries = results_io.read_results(summary_path)["rows"]
    ablation_path = directory / "ablation_summary.json"
    ablation = results_io.read_results(ablation_path)["rows"] if ablation_path.is_file() else None
    multi = results_io.read_results(directory / "multi_gpu.json")["rows"]
    labels = {b["case_id"]: b["label"] for b in analysis["bottlenecks"]}
    parts = [GENERATED_MARKER, "", "# Generated result tables", ""] + _banner(meta)
    parts += _matrix_section(summaries, labels) + _stability_section(analysis)
    parts += _decision_section(analysis) + _pairs_section(analysis) + _bottleneck_section(analysis)
    parts += _ablation_section(ablation) + _multi_gpu_section(multi)
    return "\n".join(parts)


def main(argv: Sequence[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--dir", type=Path, required=True)
    p.add_argument("--out", type=Path, default=None)
    args = p.parse_args(argv)
    out = args.out or args.dir / DEFAULT_NAME
    if not (args.dir / "analysis.json").is_file():
        print(f"{args.dir / 'analysis.json'} not found; run analyze.py first", file=sys.stderr)
        return 2
    if out.exists() and not out.read_text().startswith(GENERATED_MARKER):
        print(f"{out} exists and is hand-written (no GENERATED marker); refusing to overwrite it",
              file=sys.stderr)
        return 2
    try:
        text = render(args.dir)
    except ValueError as exc:
        print(f"cannot render: {exc}", file=sys.stderr)
        return 2
    out.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
