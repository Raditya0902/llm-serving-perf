"""Render ``results/sweep_summary.json`` as the tables of ``RESULTS.md``.

This only *formats* measured numbers.  It writes no conclusions: interpreting a
sweep needs a human who has looked at the tables, the server logs and the plots,
and a generator that "explains" numbers would invent explanations.  The
Observations section is left for the reader to fill in.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, Mapping, Sequence

from plot_results import knob_series, load_summary, value_label
from sweep_config import SWEEP_KNOBS

MISSING = "–"
DEFAULT_OUT = Path("results/RESULTS.generated.md")  # never the hand-edited RESULTS.md
COLUMNS: tuple[tuple[str, str, str], ...] = (
    # (header, summary key, format)
    ("out tok/s", "output_throughput", "{:.1f}"),
    ("req/s", "request_throughput", "{:.2f}"),
    ("mean TTFT ms", "mean_ttft_ms", "{:.1f}"),
    ("p99 TTFT ms", "p99_ttft_ms", "{:.1f}"),
    ("p99 ITL ms", "p99_itl_ms", "{:.2f}"),
    ("p99 E2EL ms", "p99_e2el_ms", "{:.0f}"),
    ("preemptions", "num_preemptions", "{:.0f}"),
    ("failed", "failed", "{:d}"),
    ("reps", "n_reps", "{:d}"),
)
OBSERVATIONS_PLACEHOLDER = (
    "_This report is generated; the numbers are not interpreted. Write observations here "
    "after reading the tables, the plots and the server logs "
    "(`results/raw/logs/*.server.log`)._"
)


def _cell(row: Mapping[str, Any], key: str, fmt: str) -> str:
    value = row.get(key)
    return MISSING if value is None else fmt.format(value)


def _knob_table(rows: Sequence[Mapping[str, Any]], knob: str) -> str | None:
    series = knob_series(rows, knob)
    if len(series) < 2:
        return None
    header = " | ".join([knob, *(c[0] for c in COLUMNS)])
    lines = [f"| {header} |", "|" + "---|" * (len(COLUMNS) + 1)]
    for row in series:
        label = value_label(row[knob]) + (" (baseline)" if row["knob"] == "baseline" else "")
        cells = [label, *(_cell(row, key, fmt) for _, key, fmt in COLUMNS)]
        lines.append("| " + " | ".join(cells) + " |")
    return f"## {knob}\n\n" + "\n".join(lines)


def render_report(rows: Sequence[Mapping[str, Any]], *, env_text: str | None) -> str:
    """Markdown report for the given summary rows."""
    if not rows:
        raise ValueError("no rows to report")

    parts = [
        "# vLLM knob sweep: results\n",
        f"Model: `{rows[0].get('model', '?')}` · one knob changed per run, all others at "
        "baseline · generated by `make_report.py` from `results/sweep_summary.json`.\n",
        "## Environment\n",
        f"```text\n{env_text.strip()}\n```\n" if env_text
        else "_environment not recorded (run `setup_gpu_host.sh`, which writes results/env.txt)_\n",
    ]
    for knob in SWEEP_KNOBS:
        table = _knob_table(rows, knob)
        if table:
            parts.append(table + "\n")

    notes = []
    if any(r.get("n_reps") == 1 for r in rows):
        notes.append("Rows with a single repetition have no variance estimate; "
                     "repeat with `--repeat 3` before trusting small differences.")
    warnings = [f"- `{r['run_id']}`: {r['failed']} failed request(s) — metrics cover "
                "only the requests that completed." for r in rows if r.get("failed")]
    if warnings:
        parts.append("## Warnings\n\n" + "\n".join(warnings) + "\n")
    if notes:
        parts.append("## Notes\n\n" + "\n".join(f"- {n}" for n in notes) + "\n")
    parts.append("## Observations\n\n" + OBSERVATIONS_PLACEHOLDER + "\n")
    return "\n".join(parts)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--summary", type=Path, default=Path("results/sweep_summary.json"))
    parser.add_argument("--env", type=Path, default=Path("results/env.txt"))
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--force", action="store_true",
                        help="overwrite --out even if it contains hand-written edits")
    args = parser.parse_args(argv)
    if not args.summary.exists():
        print(f"error: summary file {args.summary} not found; run parse_results.py first",
              file=sys.stderr)
        return 1
    if args.out.exists() and not args.force and (
        OBSERVATIONS_PLACEHOLDER not in args.out.read_text(encoding="utf-8")
    ):
        print(f"error: {args.out} exists and no longer matches a generated report "
              "(hand-edited observations?); pass --force to overwrite it", file=sys.stderr)
        return 1
    env_text = args.env.read_text(encoding="utf-8") if args.env.exists() else None
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render_report(load_summary(args.summary), env_text=env_text),
                        encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
